#!/usr/bin/env python3
"""Generate lambdalib-backed wrappers for the SonicBOOM SRAM blackboxes.

The flattened core (rtl/sonicboom.sv) leaves every Chisel memory macro as an
undefined `*_ext` blackbox (we deliberately drop Chipyard's srammap patch).
This script emits rtl/sonicboom_srams.v, defining each of those blackboxes as a
thin wrapper around a lambdalib RAM primitive so the design elaborates against
lambdalib instead of a technology macro:

  * 1RW  ports (RW0_*)          -> la_spram  (lambdalib Spram)
  * 1R1W ports (R0_* + W0_*)    -> la_dpram  (lambdalib Dpram)

Chisel uses a segmented write mask (one mask bit gates DW/MW data bits). The
lambdalib primitives take a bit mask (BYTEMASK=0), so each wrapper expands the
narrow Chisel mask to a full DW-wide bit mask. Macros with no mask write the
full word whenever the write enable is asserted.

The table below is derived from the MegaBoomV3Config collateral
(gen-collateral/*.top.mems.v). Re-run after regenerating the core if the
config or BOOM revision changes:

    python3 make_srams.py > ../rtl/sonicboom_srams.v
"""

# name -> (data_width, addr_width, mask_width)   mask_width 0 == no write mask
# Single read/write port (Chisel RW0_*), mapped to la_spram.
SPRAM = {
    "cc_dir_ext":              (136, 10, 8),
    "cc_banks_0_ext":          (64, 13, 0),
    "tag_array_ext":           (176, 6, 8),
    "tag_array_0_ext":         (160, 6, 8),
    "dataArrayB0Way_0_ext":    (64, 8, 0),
    "l2_tlb_ram_0_ext":        (45, 9, 0),
    "mem_ext":                 (64, 13, 8),
}

# Separate read port (R0_*) and write port (W0_*), mapped to la_dpram.
DPRAM = {
    "array_0_0_ext":           (128, 8, 2),
    "hi_us_ext":               (4, 7, 4),
    "hi_us_0_ext":             (4, 8, 4),
    "table_ext":               (44, 7, 4),
    "table_0_ext":             (48, 8, 4),
    "table_1_ext":             (52, 7, 4),
    "meta_0_ext":              (120, 7, 4),
    "meta_ext":                (240, 6, 0),
    "btb_0_ext":               (56, 7, 4),
    "ebtb_ext":                (40, 7, 0),
    "data_ext":                (8, 11, 4),
    "ghist_0_ext":             (72, 6, 0),
    "rob_debug_inst_mem_ext":  (128, 5, 4),
}


def bitmask(dw, mw, src):
    """Verilog fragment building a DW-wide bit mask from an MW-wide mask."""
    if mw == 0:
        return "   wire [DW-1:0] bitmask = {DW{1'b1}};\n"
    seg = dw // mw
    return (
        "   wire [DW-1:0] bitmask;\n"
        "   genvar gi;\n"
        "   generate\n"
        "      for (gi = 0; gi < DW; gi = gi + 1) begin: gmask\n"
        f"         assign bitmask[gi] = {src}[gi / {seg}];\n"
        "      end\n"
        "   endgenerate\n"
    )


def spram(name, dw, aw, mw):
    mask = "   input  [%d:0]  RW0_wmask\n" % (mw - 1) if mw else ""
    src = "RW0_wmask" if mw else ""
    return f"""module {name}(
   input  [{aw - 1}:0]  RW0_addr,
   input         RW0_clk,
   input  [{dw - 1}:0] RW0_wdata,
   output [{dw - 1}:0] RW0_rdata,
   input         RW0_en,
   input         RW0_wmode{"," if mw else ""}
{mask}   );

   localparam DW = {dw};
   localparam AW = {aw};
{bitmask(dw, mw, src)}
   la_spram #(.DW(DW), .AW(AW), .BYTEMASK(0)) mem (
      .clk     (RW0_clk),
      .ce      (RW0_en),
      .we      (RW0_en & RW0_wmode),
      .wmask   (bitmask),
      .addr    (RW0_addr),
      .din     (RW0_wdata),
      .dout    (RW0_rdata),
      .selctrl (1'b0),
      .ctrl    (32'b0),
      .status  ());

endmodule
"""


def dpram(name, dw, aw, mw):
    mask = "   input  [%d:0]  W0_mask\n" % (mw - 1) if mw else ""
    src = "W0_mask" if mw else ""
    return f"""module {name}(
   input  [{aw - 1}:0]  R0_addr,
   input         R0_clk,
   output [{dw - 1}:0] R0_data,
   input         R0_en,
   input  [{aw - 1}:0]  W0_addr,
   input         W0_clk,
   input  [{dw - 1}:0] W0_data,
   input         W0_en{"," if mw else ""}
{mask}   );

   localparam DW = {dw};
   localparam AW = {aw};
{bitmask(dw, mw, src)}
   la_dpram #(.DW(DW), .AW(AW), .BYTEMASK(0)) mem (
      .wr_clk  (W0_clk),
      .wr_ce   (W0_en),
      .wr_we   (W0_en),
      .wr_wmask(bitmask),
      .wr_addr (W0_addr),
      .wr_din  (W0_data),
      .rd_clk  (R0_clk),
      .rd_ce   (R0_en),
      .rd_addr (R0_addr),
      .rd_dout (R0_data),
      .selctrl (1'b0),
      .ctrl    (32'b0),
      .status  ());

endmodule
"""


PLUSARG = """module plusarg_reader #(
   parameter FORMAT = "borked=%d",
   parameter WIDTH = 1,
   parameter [WIDTH-1:0] DEFAULT = 0
) (
   output [WIDTH-1:0] out
);
   // Synthesis stub: the plusarg is a simulation-only construct; under
   // synthesis the reader simply drives its default (matches Chipyard's
   // `ifdef SYNTHESIS behaviour).
   assign out = DEFAULT;
endmodule
"""


def main():
    print("// Auto-generated by generation/make_srams.py -- do not edit by hand.")
    print("// lambdalib-backed wrappers for the SonicBOOM (MegaBoomV3Config) SRAM")
    print("// blackboxes plus a synthesis stub for plusarg_reader.")
    print()
    print("// ---- single-port (1RW) SRAMs -> la_spram ----")
    for name, (dw, aw, mw) in SPRAM.items():
        print()
        print(spram(name, dw, aw, mw))
    print("// ---- one-read one-write (1R1W) SRAMs -> la_dpram ----")
    for name, (dw, aw, mw) in DPRAM.items():
        print()
        print(dpram(name, dw, aw, mw))
    print("// ---- simulation-only plusarg reader (synthesis stub) ----")
    print()
    print(PLUSARG)


if __name__ == "__main__":
    main()

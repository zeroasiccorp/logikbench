"""Generic clock-constraint SDC generator for LogikBench ASIC runs.

One SDC body works for every benchmark: it creates a real clock on a 'clk'
port when present (the convention across the clocked benchmarks) and a virtual
clock otherwise, so combinational designs still have a timing reference and
their input->output paths are constrained.

The clock period is supplied in nanoseconds but emitted in the target's native
SDC time unit. OpenROAD/OpenSTA interpret 'create_clock -period' in the command
time unit they derive from the liberty (e.g. 1 ns for Nangate45 but 1 ps for
ASAP7), so the same numeric literal would otherwise mean different real
frequencies per PDK. Emitting 'period_ns / time_unit_ns' keeps the requested
frequency identical across PDKs.
"""

import os

_TEMPLATE = """\
# Generated by logikbench (sdc.py): generic LogikBench ASIC clock constraint.
# Requested period: {period_ns} ns -> {literal} in the target time unit \
({unit_ns} ns).
#
# A real clock is created on a 'clk' port when present; combinational designs
# have no clock port, so a virtual clock is created instead and the input ->
# output paths are constrained, otherwise OpenROAD reports unconstrained
# endpoints / "no clocks defined" and the flow halts.

if {{ [get_ports clk -quiet] ne "" }} {{
    create_clock -name clk -period {literal} [get_ports clk]
    set_input_delay 0.0 -clock clk [all_inputs]
    set_output_delay 0.0 -clock clk [all_outputs]
}} else {{
    create_clock -name virt -period {literal}
    set_input_delay 0.0 -clock virt [all_inputs]
    set_output_delay 0.0 -clock virt [all_outputs]
}}
"""


def render_sdc(period_ns, time_unit_ns=1.0):
    """Return SDC text for a 'period_ns' clock emitted in the target time unit.

    period_ns    : requested clock period in nanoseconds.
    time_unit_ns : the target's SDC time unit in nanoseconds (1.0 for a 1 ns
                   liberty, 0.001 for a 1 ps liberty such as ASAP7).
    """
    literal = period_ns / time_unit_ns
    return _TEMPLATE.format(period_ns="%g" % period_ns,
                            literal="%g" % literal,
                            unit_ns="%g" % time_unit_ns)


def write_sdc(path, period_ns, time_unit_ns=1.0):
    """Render the clock SDC and write it to 'path'; return 'path'."""
    parent = os.path.dirname(os.path.abspath(path))
    os.makedirs(parent, exist_ok=True)
    with open(path, "w") as f:
        f.write(render_sdc(period_ns, time_unit_ns))
    return path

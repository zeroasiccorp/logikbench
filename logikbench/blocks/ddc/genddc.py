#!/usr/bin/env python3
# Generator for the DDC numerically controlled oscillator (rtl/ddc_nco.v).
#
# Emits two modules:
#   ddc_sinrom : an NSIN-entry sine ROM as a synthesizable combinational
#                "case" (no Verilog function, no initial block) -- the exact
#                structure used by blocks/fft/genfft.py's fft_sinrom, so it
#                survives --ignore-initial and maps to LUTs (not BRAM).
#   ddc_nco    : a phase-accumulator wrapper that takes a runtime tuning word
#                "ftw" and produces cos/sin samples. cos = sin(phase + 90deg),
#                i.e. the cos lookup adds NSIN/4 to the table index -- exactly
#                like fft's fft_sinrom usage (cos = sin(x + 90deg)).
import math
import sys

NSIN = 256       # sine ROM depth (entries)
SW = 16          # sine sample width (Q1.15)
PAW = 24         # phase accumulator width
maxval = 2 ** (SW - 1) - 1
AW = int(round(math.log2(NSIN)))   # ROM address width (8 for NSIN=256)


def sinval(i):
    v = int(round(math.sin(2 * math.pi * i / NSIN) * maxval))
    if v > maxval:
        v = maxval
    if v < -maxval:
        v = -maxval
    return v


def sin_case():
    lines = []
    for i in range(NSIN):
        v = sinval(i)
        if v < 0:
            lines.append("        %d'd%d: val = -%d'sd%d;" %
                         (AW, i, SW, -v))
        else:
            lines.append("        %d'd%d: val = %d'sd%d;" %
                         (AW, i, SW, v))
    return "\n".join(lines)


HEADER = r'''//#############################################################################
// Copyright: Zero ASIC. All rights Reserved.
// Author: Andreas Olofsson
// License:  MIT (see LICENSE file in LogikBench repository)
//#############################################################################
//
// Numerically Controlled Oscillator (NCO) for the DDC front end.
//
// A PAW-bit phase accumulator advances by the runtime tuning word "ftw" on
// every valid input sample. The top AW bits of the phase index a shared
// NSIN-entry sine ROM. The cosine output reuses the same ROM by adding a
// quarter table (NSIN/4) to the index, so cos(phase) = sin(phase + 90deg)
// -- the same trick used by blocks/fft's twiddle ROM.
//
// Generated frequency: f_nco = ftw * Fs / 2^PAW.
//
// Data format: sine/cosine are Q1.15 signed fixed-point.
//
// NOTE: This file is generated by genddc.py (sine ROM). NSIN must be a power
// of two; the ROM has NSIN entries.
//
//#############################################################################

module ddc_nco
  #(parameter PAW  = %d,   // phase accumulator width
    parameter AW   = %d,    // sine ROM address width (log2 NSIN)
    parameter SW   = %d    // sine sample width (Q1.15)
    )
   (
    input                  clk,
    input                  rst,        // synchronous, active high
    input                  en,         // advance phase on valid sample
    input      [PAW-1:0]   ftw,        // frequency tuning word
    output reg signed [SW-1:0] cosout,
    output reg signed [SW-1:0] sinout
    );

   // Phase accumulator and the AW-bit ROM addresses for sin and cos.
   reg  [PAW-1:0]      phase;
   wire [AW-1:0]       sin_idx = phase[PAW-1:PAW-AW];
   wire [AW-1:0]       cos_idx = sin_idx + (1 << (AW-2));  // + NSIN/4 (90deg)
   wire signed [SW-1:0] sin_val;
   wire signed [SW-1:0] cos_val;

   ddc_sinrom u_sin (.idx(sin_idx), .val(sin_val));
   ddc_sinrom u_cos (.idx(cos_idx), .val(cos_val));

   always @(posedge clk) begin
      if (rst) begin
         phase  <= {PAW{1'b0}};
         sinout <= {SW{1'b0}};
         cosout <= {SW{1'b0}};
      end
      else if (en) begin
         phase  <= phase + ftw;
         sinout <= sin_val;
         cosout <= cos_val;
      end
   end

endmodule

//#############################################################################
// Sine ROM module: val = round(sin(2*pi*idx/NSIN)*32767). Combinational case
// (no function, no initial block); instantiated for the sin and cos lookups.
//#############################################################################
module ddc_sinrom
  (
   input  [%d:0]            idx,
   output reg signed [%d:0] val
   );
   always @* begin
      case (idx)
'''

FOOTER = r'''
         default: val = %d'sd0;
      endcase
   end
endmodule
'''


def main():
    header = HEADER % (PAW, AW, SW, AW - 1, SW - 1)
    footer = FOOTER % SW
    out = header + sin_case() + footer
    path = sys.argv[1] if len(sys.argv) > 1 else "rtl/ddc_nco.v"
    with open(path, "w") as f:
        f.write(out)
    print("wrote", path, "(%d bytes)" % len(out))


if __name__ == "__main__":
    main()
